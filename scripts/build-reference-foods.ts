const NUTRIENTS: Record<string, keyof Per100> = {
  "208": "caloriesKcal",
  "203": "proteinG",
  "205": "carbohydratesG",
  "204": "totalFatG",
  "606": "saturatedFatG",
  "291": "fiberG",
  "269": "sugarsG",
  "307": "sodiumMg",
};

interface Per100 {
  caloriesKcal: number | null;
  proteinG: number | null;
  carbohydratesG: number | null;
  totalFatG: number | null;
  saturatedFatG: number | null;
  fiberG: number | null;
  sugarsG: number | null;
  sodiumMg: number | null;
}

interface SrNutrient {
  nutrient: { number: string; unitName: string };
  amount?: number;
}
interface SrPortion {
  amount?: number;
  modifier?: string;
  measureUnit?: { name?: string };
  gramWeight: number;
}
interface SrFood {
  fdcId: number;
  description: string;
  foodNutrients: SrNutrient[];
  foodPortions?: SrPortion[];
  foodCategory?: { description: string };
  publicationDate?: string;
}

function main() {
  const input = process.argv[2];
  if (!input) {
    console.error("Usage: tsx scripts/build-reference-foods.ts <sr_legacy.json>");
    process.exit(1);
  }
  const raw = JSON.parse(readFileSync(input, "utf8")) as { SRLegacyFoods: SrFood[] };
  const byId = new Map(raw.SRLegacyFoods.map((f) => [f.fdcId, f]));

  const seen = new Set<number>();
  const out = CURATED.map((c) => {
    if (seen.has(c.fdcId)) throw new Error(`Duplicate fdcId ${c.fdcId}`);
    seen.add(c.fdcId);
    const food = byId.get(c.fdcId);
    if (!food) throw new Error(`fdcId ${c.fdcId} (${c.name}) not found in dataset`);
    const per100: Per100 = {
      caloriesKcal: null,
      proteinG: null,
      carbohydratesG: null,
      totalFatG: null,
      saturatedFatG: null,
      fiberG: null,
      sugarsG: null,
      sodiumMg: null,
    };
    for (const n of food.foodNutrients) {
      const key = NUTRIENTS[n.nutrient.number];
      if (!key || typeof n.amount !== "number") continue;
      if (n.nutrient.number === "208" && n.nutrient.unitName !== "kcal") continue;
      per100[key] = n.amount;
    }
    if (per100.caloriesKcal === null) throw new Error(`No kcal for ${c.fdcId}`);
    const portions = (food.foodPortions ?? [])
      .filter((p) => p.gramWeight > 0)
      .map((p) => {
        const unit = p.measureUnit?.name && p.measureUnit.name !== "undetermined" ? p.measureUnit.name : "";
        const label = [p.amount ?? 1, unit, p.modifier]
          .filter((x) => x !== "" && x !== undefined)
          .join(" ")
          .trim();
        return { label, grams: Math.round(p.gramWeight * 10) / 10 };
      })
      .slice(0, 6);
    return {
      id: `usda_sr:${c.fdcId}`,
      fdcId: c.fdcId,
      name: c.name,
      usdaDescription: food.description,
      aliases: c.aliases,
      state: c.state,
      kind: c.kind,
      category: c.category,
      allergens: c.allergens ?? [],
      tags: c.tags ?? [],
      per100g: per100,
      portions,
    };
  });

  const doc = {
    source: "USDA FoodData Central — SR Legacy (April 2018 release)",
    license: "Public domain (CC0 1.0). Attribution requested: U.S. Department of Agriculture, Agricultural Research Service.",
    citation: "U.S. Department of Agriculture, Agricultural Research Service. FoodData Central, 2019. fdc.nal.usda.gov.",
    basis: "per 100 g edible portion",
    generatedAt: new Date().toISOString(),
    foods: out,
  };
  const target = path.join(process.cwd(), "src/data/usda-reference-foods.json");
  writeFileSync(target, JSON.stringify(doc, null, 1) + "\n");
  console.log(`Wrote ${out.length} foods to ${target}`);
}

main();
